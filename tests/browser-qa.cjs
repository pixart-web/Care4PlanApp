/* Run only against the isolated browser fixture. Requires Playwright and Edge. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.CARE4ALL_PLAYWRIGHT || 'playwright');
const root = path.resolve(__dirname, '..');
const base = process.env.CARE4ALL_TEST_URL || 'http://127.0.0.1:8017';
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('Local fixture server only.');
const password = process.env.CARE4ALL_TEST_PASSWORD || fs.readFileSync(path.join(root, '.runtime/browser-password.txt'), 'utf8');
const out = path.join(root, 'output/playwright');
fs.mkdirSync(out, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const errors = [];
  let checks = 0;
  const pass = (name) => { checks++; console.log('PASS ' + name); };
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'pt-PT' });
    const page = await context.newPage();
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('response', (response) => { if (response.url().startsWith(base) && response.status() >= 500) errors.push('HTTP ' + response.status() + ' ' + response.url()); });
    await page.goto(base + '/index.php?page=login');
    await page.screenshot({ path: path.join(out, 'login-desktop.png') });
    await page.locator('[name=username]').fill('Andreia');
    await page.locator('[name=password]').fill(password);
    await Promise.all([page.waitForURL('**page=dashboard'), page.getByRole('button', { name: 'Entrar', exact: true }).click()]);
    pass('admin login');
    await page.screenshot({ path: path.join(out, 'dashboard-desktop.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    pass('dashboard desktop viewport');
    await page.goto(base + '/index.php?page=scales&municipality=all');
    await page.screenshot({ path: path.join(out, 'calendar-day-desktop.png') });
    assert.equal(await page.locator('.scales-v2-hour-labels span').count(), 24);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    pass('24 hour operational calendar and contained scroll');
    await page.locator('#open-new-service').click();
    assert.equal(await page.locator('#service-modal').getAttribute('hidden'), null);
    await page.locator('#patient_id').selectOption({ index: 1 });
    await page.locator('#carer_id').selectOption({ index: 1 });
    await page.locator('#service_municipality').selectOption('Lagos');
    await page.locator('#starts_at').fill('2027-01-04T09:00');
    await page.locator('#ends_at').fill('2027-01-04T10:00');
    await page.locator('#repeat-service').check();
    await page.locator('[data-weekdays="1,2,3,4,5"]').click();
    assert.equal(await page.locator('#service-submit').isDisabled(), true);
    await page.locator('#preview-service').click();
    await page.waitForFunction(() => document.querySelector('[name=preview_token]').value.length > 10);
    assert.match(await page.locator('#recurrence-preview').innerText(), /5 ocorr/);
    assert.equal(await page.locator('#service-submit').isEnabled(), true);
    await page.screenshot({ path: path.join(out, 'recurrence-preview-desktop.png') });
    pass('weekday preview enables explicit confirmation');
    await page.locator('#service_observations').fill('Fictional browser QA');
    assert.equal(await page.locator('#service-submit').isDisabled(), true);
    await page.locator('#preview-service').click();
    await page.waitForFunction(() => !document.querySelector('#service-submit').disabled);
    await Promise.all([page.waitForURL(/scale_date=2027-01-04/), page.locator('#service-submit').click()]);
    assert.match(await page.locator('body').innerText(), /5 escala/);
    pass('preview invalidation and five-service batch submission');
    await page.goto(base + '/index.php?page=scales&period=week&scale_week=2027-W01&municipality=all');
    await page.screenshot({ path: path.join(out, 'calendar-week-desktop.png') });
    pass('weekly view');
    await page.goto(base + '/index.php?page=scales&period=list&scale_date=2027-01-04&municipality=all');
    await page.locator('[data-service-id]:visible').first().click();
    const original = await page.locator('#patient_id').inputValue();
    await page.getByRole('button', { name: 'Duplicar', exact: true }).click();
    assert.equal(await page.locator('#service_id').inputValue(), '');
    assert.equal(await page.locator('#patient_id').inputValue(), original);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#service-modal').isVisible(), false);
    pass('duplicate preserves fields, clears id; Escape closes dialog');
    for (const width of [768, 390]) {
      await page.setViewportSize({ width, height: 844 });
      await page.goto(base + '/index.php?page=dashboard');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: path.join(out, 'dashboard-' + width + '.png'), fullPage: true });
      await page.goto(base + '/index.php?page=scales&municipality=all');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      if (width === 390) assert.equal(await page.locator('#scales-mobile-list').isVisible(), true);
      await page.screenshot({ path: path.join(out, 'calendar-' + width + '.png'), fullPage: true });
      pass('dashboard and calendar viewport ' + width);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    for (const view of ['patients', 'carers', 'users', 'reports', 'finances', 'settings']) {
      await page.goto(base + '/index.php?page=' + view);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, view);
    }
    pass('all admin pages mobile fit');
    const carerContext = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'pt-PT' });
    const carerPage = await carerContext.newPage();
    carerPage.on('pageerror', (error) => errors.push(error.message));
    carerPage.on('response', (response) => { if (response.url().startsWith(base) && response.status() >= 400) errors.push('CARER HTTP ' + response.status() + ' ' + response.url()); });
    await carerPage.goto(base + '/index.php?page=login');
    await carerPage.locator('[name=username]').fill('fixture-carer-1');
    await carerPage.locator('[name=password]').fill(password);
    await Promise.all([carerPage.waitForURL('**page=dashboard'), carerPage.getByRole('button', { name: 'Entrar', exact: true }).click()]);
    await carerPage.goto(base + '/index.php?page=scales');
    await carerPage.locator('.fc-timegrid-body').waitFor();
    await carerPage.locator('.fc-event').first().waitFor();
    assert.equal(await carerPage.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.match(await carerPage.locator('.fc-toolbar').innerText(), /Hoje/);
    await carerPage.screenshot({ path: path.join(out, 'carer-calendar-mobile.png'), fullPage: true });
    await carerPage.locator('.fc-event').first().click();
    await carerPage.locator('#carer-selected').waitFor();
    await carerPage.keyboard.press('Escape');
    assert.equal(await carerPage.locator('#carer-selected').isVisible(), false);
    pass('carer localized calendar, assets, mobile fit and event dialog');
    await carerContext.close();
    await context.close();
    assert.deepEqual(errors, []);
    pass('no JavaScript or HTTP 500 errors');
    console.log(`RESULT ${checks} browser checks passed`);
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
